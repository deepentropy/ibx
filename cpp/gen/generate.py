def rust_wrapper_signatures():
    text = open(os.path.join(ROOT, "src", "api", "wrapper.rs"), encoding="utf-8").read()
    text = text[text.index("pub trait Wrapper {"):text.index("/// Test helpers for Wrapper-based testing")]
    sigs = {}
    for m in re.finditer(r"fn\s+(\w+)\s*\(\s*&mut self\s*,?(.*?)\)\s*\{", text, re.S):
        params = []
        for p in split_params(" ".join(m.group(2).split())):
            name, ty = p.split(":", 1)
            params.append((name.strip(), ty.strip()))
        sigs[m.group(1)] = params
    return sigs


MASKS = {"TickAttrib": "tick_attrib", "TickAttribLast": "tick_attrib_last", "TickAttribBidAsk": "tick_attrib_bid_ask"}
ABI_RUST = {"int64_t": "i64", "double": "f64", "bool": "bool", "ibx_str": "IbxStr", "uint32_t": "u32"}


def callbacks():
    sigs = rust_wrapper_signatures()
    fields, cfields, impls, tramps, table = [], [], [], [], []
    for cb in spec.CALLBACKS:
        if cb["rust"] is None:
            continue
        rname = cb["rust"] or snake(cb["name"])
        if rname not in sigs:
            raise SystemExit("callback %s: no `%s` in the Rust wrapper" % (cb["name"], rname))
        rparams = sigs[rname]
        signature = ", ".join("%s: %s" % p for p in rparams)
        abi, rargs, pre, cdecode, cargs = [], [], [], [], []
        if cb["raw"]:
            raw = cb["raw"]
            abi = [tuple(p.rsplit(" ", 1)) for p in split_params(raw["abi"])]
            rargs = [a.strip() for a in raw["rust"].split(",")]
            pre = list(raw.get("pre", []))
            call = raw["cpp"]
        else:
            bufs, at = 0, 0
            for ctype, name in cpp_params(cb["params"]):
                b, how = bare(ctype), cb["args"].get(name)
                if how and how[0] == "cpp":
                    cargs.append(how[1])
                    continue
                if how and how[0] == "at":
                    at = how[1]
                pname, ptype = rparams[at]
                at += 1
                var = snake(name)
                if how and how[0] == "buf":
                    pre.append("s.b%d.clear(); %s(&mut W(&mut s.b%d), %s);" % (bufs, how[1], bufs, pname))
                    rargs.append("IbxStr::of_bytes(&s.b%d)" % bufs)
                    bufs += 1
                    abi.append(("ibx_str", var))
                    cdecode.append("%s v_%s; { ibx::Reader r(%s); v_%s = %s(r); }" % (how[3], var, var, var, how[2]))
                    cargs.append("v_" + var)
                elif b in ("int", "TickType", "faDataType", "long long"):
                    abi.append(("int64_t", var))
                    rargs.append("%s as i64" % pname)
                    cargs.append(var if b == "long long" else "(%s)%s" % (b, var))
                elif b == "double":
                    abi.append(("double", var))
                    rargs.append(pname)
                    cargs.append(var)
                elif b == "Decimal":
                    abi.append(("double", var))
                    rargs.append(pname if ptype == "f64" else "%s as f64" % pname)
                    cargs.append("ibx::decimalFromDouble(%s)" % var)
                elif b == "bool":
                    abi.append(("bool", var))
                    rargs.append(pname)
                    cargs.append(var)
                elif b == "std::string":
                    abi.append(("ibx_str", var))
                    rargs.append("IbxStr::of(%s)" % pname)
                    cargs.append("ibx::str(%s)" % var)
                elif b in MASKS:
                    abi.append(("uint32_t", var))
                    rargs.append("crate::capi::mask_%s(%s)" % (MASKS[b], pname))
                    cargs.append("ibx::%s(%s)" % (MASKS[b], var))
                elif has_codec(b, "out"):
                    pre.append("s.b%d.clear(); w_%s(&mut W(&mut s.b%d), %s);" % (bufs, snake(b), bufs, pname))
                    rargs.append("IbxStr::of_bytes(&s.b%d)" % bufs)
                    bufs += 1
                    abi.append(("ibx_str", var))
                    cdecode.append("%s v_%s; { ibx::Reader r(%s); ibx::read(r, v_%s); }" % (b, var, var, var))
                    cargs.append("v_" + var)
                elif b.startswith("std::vector<") and has_codec(b[12:-1], "out"):
                    elem = b[12:-1]
                    pre.append("s.b%d.clear(); { let w = &mut W(&mut s.b%d); w.n(%s.len()); for e in %s.iter() { w_%s(w, e); } }"
                               % (bufs, bufs, pname, pname, snake(elem)))
                    rargs.append("IbxStr::of_bytes(&s.b%d)" % bufs)
                    bufs += 1
                    abi.append(("ibx_str", var))
                    cdecode.append("%s v_%s; { ibx::Reader r(%s); ibx::readVec(r, v_%s); }" % (b, var, var, var))
                    cargs.append("v_" + var)
                else:
                    raise SystemExit("callback %s: parameter type %s" % (cb["name"], ctype))
            if bufs > 3:
                raise SystemExit("callback %s: more than three encoded parameters" % cb["name"])
            call = "s->w->%s(%s);" % (cb["name"], ", ".join(cargs))
        fields.append("    pub %s: unsafe extern \"C\" fn(*mut c_void%s)," % (rname, "".join(", " + ABI_RUST[t] for t, _ in abi)))
        cfields.append("  void (*%s)(void* user%s);" % (rname, "".join(", %s %s" % a for a in abi)))
        impls.append("    fn %s(&mut self%s) {\n%s        unsafe { (self.cb.%s)(self.user%s) }\n    }\n" % (
            rname, ", " + signature if signature else "",
            ("        let s = &mut self.s;\n" + "".join("        %s\n" % p for p in pre)) if pre else "",
            rname, "".join(", " + a for a in rargs)))
        tramps.append("static void cb_%s(void* user%s) noexcept {\n  ibx::Sink* s = static_cast<ibx::Sink*>(user);\n  try {\n%s    %s\n  } catch (...) { s->failed(); }\n}\n" % (
            rname, "".join(", %s %s" % a for a in abi), "".join("    %s\n" % d for d in cdecode), call))
        table.append("  &cb_%s," % rname)
        TRAMPOLINES.append(dict(cb=cb, rname=rname, abi=abi, cdecode=cdecode, cargs=cargs, call=call))
    return "\n".join(fields), "\n".join(cfields), "\n".join(impls), "\n".join(tramps), "\n".join(table)


