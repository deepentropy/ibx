def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def cpp_params(text):
    out = []
    for p in split_params(text):
        ctype, name = p.rsplit(" ", 1)
        if name.startswith("&"):
            ctype, name = ctype + "&", name[1:]
        out.append((ctype.strip(), name))
    return out


def bare(ctype):
    return re.sub(r"^const\s+|\s*&$", "", ctype).strip()


ID_NAMES = ("reqId", "id", "requestId", "orderId", "reqid")


