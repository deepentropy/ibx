def test_callbacks():
    """The Rust calls of every callback and the C++ wrapper that checks them."""
    sigs = rust_wrapper_signatures()
    by_type = rust_struct_by_type()
    fire, methods, expected, renamed = [], [], [], []
    for cb in spec.CALLBACKS:
        params = cpp_params(cb["params"])
        body = ['hit("%s");' % cb["name"]]
        if cb["rust"] is None:
            body += ["(void)%s;" % n for _, n in params]
        else:
            rname = cb["rust"] or snake(cb["name"])
            rparams = sigs[rname]
            if cb["plain"]:
                expected.append(cb["name"])
            # The C++ type each Rust parameter is given as, for the small enumerations.
            enum_of = {}
            if not cb["raw"]:
                at = 0
                for ctype, name in params:
                    how = cb["args"].get(name)
                    if how and how[0] == "cpp":
                        continue
                    if how and how[0] == "at":
                        at = how[1]
                    enum_of[at] = bare(ctype)
                    at += 1
            args = []
            for k, (pname, ptype) in enumerate(rparams):
                key = pname.lstrip("_")
                inner = ptype.lstrip("&").rsplit("::", 1)[-1]
                if (rname, key) in spec.FIRE_AT:
                    args.append(spec.FIRE_AT[(rname, key)][0])
                elif enum_of.get(k) == "TickType":
                    args.append('(tv_i("%s", 0) %% 100) as %s' % (key, ptype))
                elif enum_of.get(k) == "faDataType":
                    args.append("1")
                elif ptype in ("i64", "i32"):
                    args.append('tv_i("%s", 0) as %s' % (key, ptype))
                elif ptype == "f64":
                    args.append('tv_f("%s", 0)' % key)
                elif ptype == "bool":
                    args.append('tv_b("%s", 0)' % key)
                elif ptype == "&str":
                    args.append('&tv_s("%s", 0)' % key)
                elif ptype in spec.FIRE:
                    args.append(spec.FIRE[ptype][0])
                elif ptype.startswith("&[") and ptype[2:-1].rsplit("::", 1)[-1] in by_type:
                    e = snake(by_type[ptype[2:-1].rsplit("::", 1)[-1]]["name"])
                    args.append("&[fill_%s(1), fill_%s(2)]" % (e, e))
                elif ptype.startswith("&") and inner in by_type:
                    args.append("&fill_%s(1)" % snake(by_type[inner]["name"]))
                else:
                    raise SystemExit("test of callback %s: no value for %s: %s" % (cb["name"], pname, ptype))
            fire.append("        w.%s(%s);" % (rname, ", ".join(args)))
            if not cb["plain"]:
                continue
            if cb["raw"]:
                body.append('expect(fails, "%s", %s);' % (cb["name"], cb["raw"]["check"]))
            else:
                at = 0
                for ctype, name in params:
                    b, how = bare(ctype), cb["args"].get(name)
                    where = '"%s.%s"' % (cb["name"], name)
                    if how and how[0] == "cpp":
                        body.append("(void)%s;" % name)
                        continue
                    if how and how[0] == "at":
                        at = how[1]
                    pname, ptype = rparams[at]
                    at += 1
                    key = pname.lstrip("_")
                    if snake(name) != key:
                        renamed.append("%s: %s <- %s" % (cb["name"], name, key))
                    special = spec.FIRE_AT.get((rname, key)) or (spec.FIRE.get(ptype) if (how and how[0] == "buf") or b in MASKS else None)
                    if special:
                        body.append("{ const auto& v = %s; expect(fails, %s, %s); }" % (name, where, special[1]))
                    elif b == "TickType":
                        body.append('expect(fails, %s, (long long)%s == tvI("%s", 0) %% 100);' % (where, name, key))
                    elif b == "faDataType":
                        body.append("expect(fails, %s, %s == GROUPS);" % (where, name))
                    elif b in ("int", "long long"):
                        body.append('expect(fails, %s, (long long)%s == tvI("%s", 0));' % (where, name, key))
                    elif b == "double":
                        body.append('expect(fails, %s, %s == tvF("%s", 0));' % (where, name, key))
                    elif b == "Decimal":
                        body.append('expect(fails, %s, ibx::decimalToDoubleOrMax(%s) == tvF("%s", 0));' % (where, name, key))
                    elif b == "bool":
                        body.append('expect(fails, %s, %s == tvB("%s", 0));' % (where, name, key))
                    elif b == "std::string":
                        body.append('expect(fails, %s, %s == tvS("%s", 0));' % (where, name, key))
                    elif has_codec(b, "out"):
                        body.append("check(%s, 1, %s, fails);" % (name, where))
                    elif b.startswith("std::vector<") and has_codec(b[12:-1], "out"):
                        body.append("expect(fails, %s, %s.size() == 2); for (size_t k = 0; k < %s.size(); ++k) check(%s[k], 1 + (int)k, %s, fails);"
                                    % (where, name, name, name, where))
                    else:
                        raise SystemExit("test of callback %s: no check for %s" % (cb["name"], ctype))
        methods.append("  void %s(%s) override {\n%s\n  }" % (cb["name"], cb["params"], "\n".join("    " + l for l in body)))
    return "\n".join(fire), "\n".join(methods), expected, renamed


