def requests():
    rust, cdecl, cpp, inc = [], [], [], []
    for q in spec.REQUESTS:
        params = cpp_params(q["params"])
        cname = "ibx_" + snake(q["name"])
        ident = next((n for _, n in params if n in ID_NAMES), None)
        err_id = "(int)%s" % ident if ident else "-1"
        rust_id = snake(ident) if ident else "-1"
        r_params, r_pre, c_params, call_args, c_pre, unused = [], [], [], [], [], []
        for ctype, name in params:
            var, b = snake(name), bare(ctype)
            if not re.search(r"\b%s\b" % re.escape(var), q["call"]) and name != ident:
                unused.append(name)
                continue
            if b in ("int", "faDataType"):
                r_params.append("%s: i64" % var)
                c_params.append("int64_t %s" % var)
                call_args.append("(int64_t)%s" % name)
            elif b == "bool":
                r_params.append("%s: bool" % var)
                c_params.append("bool %s" % var)
                call_args.append(name)
            elif b == "double":
                r_params.append("%s: f64" % var)
                c_params.append("double %s" % var)
                call_args.append(name)
            elif b == "std::string":
                r_params.append("%s: IbxStr" % var)
                c_params.append("ibx_str %s" % var)
                call_args.append("ibx::view(%s)" % name)
                r_pre.append("let %s = unsafe { %s.text() };\n        let %s = &*%s;" % (var, var, var, var))
            elif b == "TagValueListSPtr":
                r_params.append("%s: IbxStr" % var)
                c_params.append("ibx_str %s" % var)
                c_pre.append("ibx::Buf b_%s; ibx::writeTags(b_%s.w, %s);" % (name, name, name))
                call_args.append("b_%s.view()" % name)
                r_pre.append("let %s = crate::capi::read_tags(unsafe { %s.bytes() });" % (var, var))
            elif has_codec(b, "in"):
                r_params.append("%s: IbxStr" % var)
                c_params.append("ibx_str %s" % var)
                c_pre.append("ibx::Buf b_%s; ibx::write(b_%s.w, %s);" % (name, name, name))
                call_args.append("b_%s.view()" % name)
                r_pre.append("let mut rd = R::new(unsafe { %s.bytes() });\n        let %s = r_%s(&mut rd);\n"
                             "        if let Some((code, text)) = rd.refused { return crate::capi::refuse(c, %s, code, text); }"
                             % (var, var, snake(b), rust_id))
            else:
                raise SystemExit("request %s: parameter type %s" % (q["name"], ctype))
        rust.append(
            "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn %s(h: *mut IbxClient%s) -> i32 {\n"
            "    crate::capi::request(h, |c, w| {\n        let _ = &w;\n%s        (%s).status()\n    })\n}\n"
            % (cname, "".join(", " + p for p in r_params), "".join("        %s\n" % p for p in r_pre), q["call"]))
        cdecl.append("int32_t %s(ibx_client* h%s);" % (cname, "".join(", " + p for p in c_params)))
        cpp.append("void EClient::%s(%s) {\n%s  if (!ibxReady(%s)) return;\n%s  ibxDone(%s, %s(m_handle%s));\n}\n" % (
            q["name"], q["params"],
            "".join("  (void)%s;\n" % u for u in unused),
            err_id,
            "".join("  %s\n" % p for p in c_pre),
            err_id, cname, "".join(", " + a for a in call_args)))
        inc.append("  void %s(%s);" % (q["name"], q["params"]))
    return "\n".join(rust), "\n".join(cdecl), "\n".join(cpp), "\n".join(inc)


