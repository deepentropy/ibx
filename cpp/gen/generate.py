PLAIN = {
    "int": "int", "long long": "int", "double": "f", "bool": "b", "std::string": "s", "Decimal": "dec",
    "TagValueListSPtr": "tags",
}

# kind -> C++ write, C++ read, Rust write, Rust read
CODEC = {
    "int": ("w.i({c});", "{c} = ({t})r.i();", "w.i({r} as i64);", "{r} = r.i() as _;"),
    "enum": ("w.i((long long){c});", "{c} = ({t})r.i();", "w.i({r} as i64);", "{r} = r.i() as _;"),
    "f": ("w.f({c});", "{c} = r.f();", "w.f({r});", "{r} = r.f();"),
    "b": ("w.b({c});", "{c} = r.b();", "w.b({r});", "{r} = r.b();"),
    "s": ("w.s({c});", "{c} = r.s();", "w.s(&{r});", "{r} = r.s();"),
    "dec": ("w.f(ibx::decimalToDoubleOrMax({c}));", "{c} = ibx::decimalFromDouble(r.f());", "w.f({r});", "{r} = r.f();"),
    "dectext": ("", "{c} = ibx::decimalFromText(r.s());", "w.s(&{r});", ""),
    "tags": ("ibx::writeTags(w, {c});", "ibx::readTags(r, {c});",
             "w.n({r}.len()); for e in &{r} {{ w_tag_value(w, e); }}",
             "{{ let n = r.n(); {r} = (0..n).map(|_| r_tag_value(r)).collect(); }}"),
    "splist": ("ibx::writeList(w, {c});", "ibx::readList(r, {c});",
               "w.n({r}.len()); for e in &{r} {{ w_{e}(w, e); }}",
               "{{ let n = r.n(); {r} = (0..n).map(|_| r_{e}(r)).collect(); }}"),
    "uptr": ("w.b(bool({c})); if ({c}) write(w, *{c});", "if (r.b()) {{ {c}.reset(new {E}()); read(r, *{c}); }}",
             "w.b({r}.is_some()); if let Some(e) = &{r} {{ w_{e}(w, e); }}",
             "{r} = if r.b() {{ Some(r_{e}(r)) }} else {{ None }};"),
    "struct": ("write(w, {c});", "read(r, {c});", "w_{e}(w, &{r});", "{r} = r_{e}(r);"),
}


def members(st):
    out = []
    for line in st["members"].strip().splitlines():
        decl, _, notes = line.partition(";;")
        decl = decl.strip()
        notes = dict((n.split("=", 1) + [""])[:2] for n in notes.split())
        decl, _, default = decl.partition(" = ")
        ctype, name = decl.rsplit(" ", 1)
        m = dict(ctype=ctype.strip(), name=name, default=default.strip(), notes=notes, elem="")
        if "none" in notes or st["dir"] == "def":
            m["kind"] = None
        elif "x" in notes:
            m["kind"] = "x"
        else:
            for k in ("splist", "uptr", "struct"):
                if k in notes:
                    m["kind"], m["elem"] = k, notes[k]
                    break
            else:
                m["kind"] = "enum" if "enum" in notes else "dectext" if "dectext" in notes else PLAIN[m["ctype"]]
        m["rust"] = notes.get("r") or snake(name)
        m["dir"] = notes.get("d", "both")
        out.append(m)
    return out


def codec(m, which):
    """The statement of one member: which = 0 C++ write, 1 C++ read, 2 Rust write, 3 Rust read."""
    if m["kind"] is None:
        return ""
    template = spec.CUSTOM[m["notes"]["x"]][which] if m["kind"] == "x" else CODEC[m["kind"]][which]
    return template.format(c="x." + m["name"], r="x." + m["rust"], t=m["ctype"], e=snake(m["elem"]), E=m["elem"])


def crosses(st, m, way):
    """Whether a member crosses: way "in" is C++ to Rust."""
    return m["kind"] is not None and st["dir"] in ("both", way) and m["dir"] in ("both", way)


def struct_definition(st):
    ms = members(st)
    lines = ["struct %s\n{" % st["name"]]
    if st["head"]:
        lines.append(st["head"].rstrip("\n"))
    for m in ms:
        lines.append("  %s %s%s;" % (m["ctype"], m["name"], " = " + m["default"] if m["default"] else ""))
    owned = [m for m in ms if m["ctype"].startswith("std::unique_ptr<")]
    if owned:
        # A member that owns its object is copied with the object.
        n = st["name"]

        def copy(m):
            if m in owned:
                inner = m["ctype"][len("std::unique_ptr<"):-1]
                return "o.%s ? new %s(*o.%s) : nullptr" % (m["name"], inner, m["name"])
            return "o." + m["name"]
        lines.append("")
        lines.append("  %s() = default;" % n)
        lines.append("  %s(const %s& o)\n    : %s\n  {}" % (n, n, "\n    , ".join("%s(%s)" % (m["name"], copy(m)) for m in ms)))
        lines.append("  %s& operator=(const %s& o)\n  {\n    if (this != &o) {" % (n, n))
        for m in ms:
            lines.append("      %s.reset(%s);" % (m["name"], copy(m)) if m in owned else "      %s = o.%s;" % (m["name"], m["name"]))
        lines.append("    }\n    return *this;\n  }")
        lines.append("  %s(%s&&) = default;\n  %s& operator=(%s&&) = default;" % (n, n, n, n))
    if st["tail"]:
        lines.append("")
        lines.append(st["tail"].rstrip("\n"))
    lines.append("};")
    return "\n".join(lines)


def structure_headers():
    for header, info in spec.HEADERS.items():
        guard = "IBX_" + re.sub(r"\W", "_", header).upper()
        parts = ["// %s" % NOTE, "#pragma once", "#ifndef %s" % guard, "#define %s" % guard, ""]
        parts += ["#include %s" % i for i in info.get("includes", [])]
        if info.get("includes"):
            parts.append("")
        if info.get("before"):
            parts += [info["before"].rstrip("\n"), ""]
        for st in spec.STRUCTS:
            if st["header"] != header:
                continue
            between = info.get("between", {}).get(st["name"])
            if between:
                parts += [between.rstrip("\n"), ""]
            parts += [struct_definition(st), ""]
        if info.get("after"):
            parts += [info["after"].rstrip("\n"), ""]
        parts += ["#endif", ""]
        OUT["cpp/include/" + header] = "\n".join(parts)


def cpp_codecs():
    out = []
    for st in spec.STRUCTS:
        if st["dir"] == "def":
            continue
        ms = members(st)
        if st["dir"] in ("both", "in"):
            body = [codec(m, 0) for m in ms if crosses(st, m, "in")]
            out.append("void write(Writer& w, const %s& x) {\n%s\n}\n" % (st["name"], "\n".join("  " + b for b in body if b)))
        if st["dir"] in ("both", "out"):
            body = [codec(m, 1) for m in ms if crosses(st, m, "out")]
            out.append("void read(Reader& r, %s& x) {\n%s\n}\n" % (st["name"], "\n".join("  " + b for b in body if b)))
    return "\n".join(out)


def cpp_codec_declarations():
    out = []
    for st in spec.STRUCTS:
        if st["dir"] in ("both", "in"):
            out.append("void write(Writer& w, const %s& x);" % st["name"])
        if st["dir"] in ("both", "out"):
            out.append("void read(Reader& r, %s& x);" % st["name"])
    return "\n".join(out)


def rust_codecs():
    out = []
    for st in spec.STRUCTS:
        if st["dir"] == "def":
            continue
        ms = members(st)
        name, ty = snake(st["name"]), st["rust"]
        if st["dir"] in ("both", "out"):
            body = [codec(m, 2) for m in ms if crosses(st, m, "out")]
            out.append("pub(crate) fn w_%s(w: &mut W, x: &%s) {\n%s\n}\n" % (name, ty, "\n".join("    " + b for b in body if b)))
        if st["dir"] in ("both", "in"):
            body = [codec(m, 3) for m in ms if crosses(st, m, "in")]
            out.append("pub(crate) fn r_%s(r: &mut R) -> %s {\n    let mut x = <%s>::default();\n%s\n    x\n}\n" % (
                name, ty, ty, "\n".join("    " + b for b in body if b)))
    return "\n".join(out)


def has_codec(name, way):
    return any(st["name"] == name and st["dir"] in ("both", way) for st in spec.STRUCTS)


